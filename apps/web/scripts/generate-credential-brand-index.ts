// @effect-diagnostics nodeBuiltinImport:off globalConsole:off
/**
 * Regenerates `packages/shared/src/credentialBrandIndex.ts` from the installed
 * `simple-icons` package.
 *
 *   vp run --filter @t3tools/web credentials:brand-index
 *
 * The committed index holds only what matching and the picker need (slug, title,
 * hex, aliases). The icon path data stays in the package so Vite can emit one
 * lazy chunk per brand; a runtime import of the package would pull ~3.4 MB into
 * whichever chunk matched.
 */
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";

import simpleIcons from "simple-icons/icons.json" with { type: "json" };

interface SimpleIconRecord {
  readonly title: string;
  readonly slug: string;
  readonly hex: string;
  readonly aliases?: { readonly aka?: ReadonlyArray<string> } | undefined;
}

/**
 * Names people actually type, for brands whose simple-icons title is not the
 * product name they hold a credential for. Kept here rather than in the matcher
 * so a regeneration cannot drop them.
 */
const EXTRA_ALIASES: Readonly<Record<string, ReadonlyArray<string>>> = {
  anthropic: ["Claude API", "Anthropic API"],
  appstore: ["App Store Connect", "App Store Connect API", "Transporter"],
  expo: ["EAS", "Expo Application Services"],
  googlecloud: ["GCP", "Google Cloud Platform"],
};

const OUTPUT_PATH = NodePath.join(
  import.meta.dirname,
  "../../../packages/shared/src/credentialBrandIndex.ts",
);

/** A template literal is ~40% smaller than one object literal per brand. */
function escapeForTemplate(value: string): string {
  return value.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
}

function row(icon: SimpleIconRecord): string {
  const aliases = [...(icon.aliases?.aka ?? []), ...(EXTRA_ALIASES[icon.slug] ?? [])].filter(
    (alias) => alias.trim().length > 0,
  );
  const cells = [icon.slug, icon.title, icon.hex.toUpperCase(), aliases.join("|")];
  return escapeForTemplate(cells.join("\t"));
}

const icons = (simpleIcons as ReadonlyArray<SimpleIconRecord>)
  .map(row)
  .sort((left, right) => left.localeCompare(right));

// The package does not export its own manifest; resolve its data file first.
const packageRoot = new URL("../", import.meta.resolve("simple-icons/icons.json"));
const simpleIconsVersion = (
  JSON.parse(NodeFS.readFileSync(new URL("package.json", packageRoot), "utf8")) as {
    readonly version: string;
  }
).version;

const output = `// Generated by \`vp run --filter @t3tools/web credentials:brand-index\`. Do not edit by hand.
// Source: simple-icons ${simpleIconsVersion} (CC0-1.0).
// Four tab-separated cells per brand: slug, title, hex without \`#\`, \`|\`-separated aliases.

/** One line per brand, split by the matcher in \`credentialBrand.ts\`. */
export const CREDENTIAL_BRAND_ROWS = \`${icons.join("\n")}
\`;
`;

NodeFS.writeFileSync(OUTPUT_PATH, output);
console.log(`Wrote ${icons.length} brands to ${NodePath.relative(process.cwd(), OUTPUT_PATH)}.`);
